// FEAT-091: the MentisTranslations build tool, between the JSON files of translations/ and Qt.
//
//   MentisTranslations sync <lupdate.ts> <translations folder>
//       Every <code>.json and template.json take the texts lupdate found in the code: new ones
//       empty, vanished ones removed, the others keep their translation.
//   MentisTranslations ts <code>.json <out.ts> <code>
//       The .ts that lrelease compiles into the app.
//   MentisTranslations offered <percent> <out.h> <code>.json...
//       The header listing the languages at least <percent> translated (written only if it changes).
//   MentisTranslations from-ts <in.ts> <out.json>
//       Converts a Qt Linguist file (the migration of 2026-11-02, or a volunteer's .ts).
#include "translationfiles.h"

#include <QCoreApplication>
#include <QDir>
#include <QFile>
#include <QFileInfo>
#include <QSaveFile>

#include <cstdio>

namespace {

using namespace TranslationFiles;

int fail(const QString &message) {
    std::fprintf(stderr, "MentisTranslations: %s\n", qPrintable(message));
    return 1;
}

// Replaces the file only if its content changes: the build does not redo what depends on it.
bool write(const QString &path, const QByteArray &content, QString *error) {
    QFile current(path);
    if (current.open(QIODevice::ReadOnly) && current.readAll() == content) return true;
    current.close();
    QDir().mkpath(QFileInfo(path).absolutePath());
    QSaveFile file(path);
    if (!file.open(QIODevice::WriteOnly) || file.write(content) != content.size() || !file.commit()) {
        *error = QStringLiteral("cannot write %1").arg(path);
        return false;
    }
    return true;
}

QString languageOf(const QString &jsonPath) { return QFileInfo(jsonPath).completeBaseName(); }

int sync(const QString &lupdateTs, const QString &folder) {
    QString error;
    QList<Message> code;
    if (!readTs(lupdateTs, &code, &error)) return fail(error);
    QStringList files = QDir(folder).entryList({QStringLiteral("*.json")}, QDir::Files, QDir::Name);
    if (!files.contains(QStringLiteral("template.json"))) files.append(QStringLiteral("template.json"));
    for (const QString &name : files) {
        const QString path = QDir(folder).filePath(name);
        QList<Message> translated;
        if (QFileInfo::exists(path) && !readJsonFile(path, &translated, &error)) return fail(error);
        // The template stays empty: it is what a new language starts from.
        const QList<Message> merged = merge(code, name == QLatin1String("template.json") ? QList<Message>() : translated);
        if (!write(path, writeJson(merged), &error)) return fail(error);
        const Completeness count = completeness(merged);
        std::printf("%s: %d/%d texts translated\n", qPrintable(name), count.done, count.total);
    }
    return 0;
}

int toTs(const QString &json, const QString &out, const QString &language) {
    QString error;
    QList<Message> messages;
    if (!readJsonFile(json, &messages, &error)) return fail(error);
    return write(out, writeTs(messages, language), &error) ? 0 : fail(error);
}

int offeredHeader(int percent, const QString &out, const QStringList &jsons) {
    QStringList codes;
    for (const QString &json : jsons) {
        QString error;
        QList<Message> messages;
        if (!readJsonFile(json, &messages, &error)) return fail(error);
        if (offered(completeness(messages), percent)) codes.append(languageOf(json));
    }
    codes.sort();
    QStringList literals;
    for (const QString &code : codes) literals.append(QStringLiteral("QStringLiteral(\"%1\")").arg(code));
    const QByteArray header = QStringLiteral(
        "#pragma once\n"
        "// Generated by MentisTranslations from translations/<code>.json: the languages offered in\n"
        "// Settings, at least %1% translated (FEAT-046, FEAT-091).\n"
        "#define MENTIS_OFFERED_TRANSLATIONS %2\n").arg(percent).arg(literals.join(QStringLiteral(", "))).toUtf8();
    QString error;
    return write(out, header, &error) ? 0 : fail(error);
}

int fromTs(const QString &ts, const QString &out) {
    QString error;
    QList<Message> messages;
    if (!readTs(ts, &messages, &error)) return fail(error);
    return write(out, writeJson(messages), &error) ? 0 : fail(error);
}

}  // namespace

int main(int argc, char *argv[]) {
    QCoreApplication app(argc, argv);
    const QStringList args = app.arguments().mid(1);
    const QString command = args.value(0);
    if (command == QLatin1String("sync") && args.size() == 3) return sync(args[1], args[2]);
    if (command == QLatin1String("ts") && args.size() == 4) return toTs(args[1], args[2], args[3]);
    if (command == QLatin1String("offered") && args.size() >= 3) return offeredHeader(args[1].toInt(), args[2], args.mid(3));
    if (command == QLatin1String("from-ts") && args.size() == 3) return fromTs(args[1], args[2]);
    return fail(QStringLiteral("usage: sync <lupdate.ts> <folder> | ts <json> <out.ts> <code> | "
                               "offered <percent> <out.h> <json>... | from-ts <in.ts> <out.json>"));
}
